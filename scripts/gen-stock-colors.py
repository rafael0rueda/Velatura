#!/usr/bin/env python3
"""Read libadwaita's own values for the named colours a theme overrides,
for the light and the dark style, from a clean settings folder.

    scripts/gen-stock-colors.py            print the Rust table
    scripts/gen-stock-colors.py --check F  fail if F differs from it

The app uses the table to keep its own window in stock colours whatever
theme is applied. Opens no window; needs a display. The accent colours are
left out: the app takes those from the system accent at run time.
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PROBE = r'''
import os, sys, warnings
import gi
gi.require_version("Gtk", "4.0"); gi.require_version("Adw", "1")
from gi.repository import Adw, Gtk
warnings.simplefilter("ignore")
Adw.init()
Adw.StyleManager.get_default().set_color_scheme(
    Adw.ColorScheme.FORCE_DARK if sys.argv[1] == "dark" else Adw.ColorScheme.FORCE_LIGHT)
ctx = Gtk.Window().get_style_context()
for name in sys.argv[2:]:
    ok, c = ctx.lookup_color(name)
    if not ok:
        print(name, "-"); continue
    # Colours libadwaita mixes in Oklab can fall outside sRGB; GTK clips
    # them when drawing, so the table does too.
    r, g, b = (min(255, max(0, round(v * 255))) for v in (c.red, c.green, c.blue))
    print(name, "#%02x%02x%02x" % (r, g, b) if c.alpha >= 0.999
          else "rgba(%d, %d, %d, %s)" % (r, g, b, ("%.3f" % c.alpha).rstrip("0").rstrip(".")))
'''


def names():
    golden = os.path.join(HERE, "../crates/velatura-theme/tests/golden/ember.gtk.css")
    found = re.findall(r"@define-color (\w+) ", open(golden).read())
    return [n for n in found if not n.startswith("accent_")]


def probe(scheme):
    env = dict(os.environ, XDG_CONFIG_HOME=tempfile.mkdtemp(), GTK_A11Y="none",
               GSETTINGS_BACKEND="memory", GTK_THEME="")
    env.pop("GTK_THEME")
    out = subprocess.check_output([sys.executable, "-c", PROBE, scheme] + names(), env=env, text=True)
    return [line.split(" ", 1) for line in out.splitlines()]


def table():
    version = subprocess.check_output(["pkg-config", "--modversion", "libadwaita-1"], text=True).strip()
    lines = [
        "//! libadwaita's own values for the named colours a theme overrides.",
        "//!",
        f"//! Generated by scripts/gen-stock-colors.py from libadwaita {version}.",
        "//! Do not edit by hand.",
        "",
    ]
    for scheme in ("light", "dark"):
        rows = probe(scheme)
        lines.append(f"pub const {scheme.upper()}: [(&str, &str); {len(rows)}] = [")
        lines += [f'    ("{name}", "{value}"),' for name, value in rows]
        lines.append("];")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


if __name__ == "__main__":
    text = table()
    if len(sys.argv) == 3 and sys.argv[1] == "--check":
        same = open(sys.argv[2]).read() == text
        print("stock colour table matches this libadwaita" if same
              else f"{sys.argv[2]} differs from this libadwaita: regenerate it, or note the version difference")
        sys.exit(0 if same else 1)
    sys.stdout.write(text)
