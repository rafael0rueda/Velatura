//! Renderer for Ghostty: colours in, the text of `velatura.conf` out.

use std::fmt::Write;

use crate::Resolved;

/// Bumped whenever the set of keys or their mapping changes.
pub const FORMAT: u32 = 1;

/// The keys this renderer sets besides the 16 `palette` entries.
pub const KEYS: [&str; 6] = [
    "background",
    "foreground",
    "cursor-color",
    "cursor-text",
    "selection-background",
    "selection-foreground",
];

pub fn render(theme: &Resolved<'_>) -> String {
    let ui = &theme.colors.ui;
    let named = [
        ui.bg,
        ui.fg,
        ui.cursor,
        ui.cursor_fg,
        ui.selection_bg,
        ui.selection_fg,
    ];
    let mut out = String::new();
    out.push_str("# Generated by Velatura. Edits to this file are replaced on the next apply.\n");
    let _ = writeln!(
        out,
        "# theme {} fingerprint {} format {FORMAT}",
        theme.label(),
        theme.fingerprint()
    );
    for (key, color) in KEYS.iter().zip(named) {
        let _ = writeln!(out, "{key} = {}", color.hex());
    }
    for (i, color) in theme.colors.ansi.iter().enumerate() {
        let _ = writeln!(out, "palette = {i}={}", color.hex());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bundled;

    #[test]
    fn golden() {
        let themes = bundled::themes();
        let golden = [
            include_str!("../tests/golden/aetherius.ghostty.conf"),
            include_str!("../tests/golden/ember.ghostty.conf"),
        ];
        for (theme, expected) in themes.iter().zip(golden) {
            assert_eq!(render(&Resolved::new(theme, None).unwrap()), expected);
        }
    }
}
