//! Renderer for Kitty: colours in, the text of `velatura.conf` out.

use std::fmt::Write;

use crate::Resolved;

/// Bumped whenever the set of keys or their mapping changes.
pub const FORMAT: u32 = 1;

/// Every key this renderer sets, in output order. The connector uses the
/// list to find lines in `kitty.conf` that would override the theme.
pub const KEYS: [&str; 30] = [
    "foreground",
    "background",
    "selection_foreground",
    "selection_background",
    "cursor",
    "cursor_text_color",
    "url_color",
    "active_border_color",
    "inactive_border_color",
    "active_tab_foreground",
    "active_tab_background",
    "inactive_tab_foreground",
    "inactive_tab_background",
    "tab_bar_background",
    "color0",
    "color1",
    "color2",
    "color3",
    "color4",
    "color5",
    "color6",
    "color7",
    "color8",
    "color9",
    "color10",
    "color11",
    "color12",
    "color13",
    "color14",
    "color15",
];

pub fn render(theme: &Resolved<'_>) -> String {
    let ui = &theme.colors.ui;
    let named = [
        ui.fg,
        ui.bg,
        ui.selection_fg,
        ui.selection_bg,
        ui.cursor,
        ui.cursor_fg,
        ui.link,
        ui.accent,
        ui.border,
        ui.fg,
        ui.surface,
        ui.fg_subtle,
        ui.bg_dim,
        ui.bg_dim,
    ];
    let mut out = String::new();
    out.push_str("# Generated by Velatura. Edits to this file are replaced on the next apply.\n");
    let _ = writeln!(
        out,
        "# theme {} fingerprint {} format {FORMAT}",
        theme.label(),
        theme.fingerprint()
    );
    let colors = named.into_iter().chain(theme.colors.ansi);
    for (key, color) in KEYS.iter().zip(colors) {
        let _ = writeln!(out, "{key} {}", color.hex());
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{bundled, parse_theme};

    #[test]
    fn golden_aetherius() {
        let themes = bundled::themes();
        let theme = Resolved::new(&themes[0], None).unwrap();
        assert_eq!(
            render(&theme),
            include_str!("../tests/golden/aetherius.kitty.conf")
        );
    }

    #[test]
    fn golden_ember() {
        let themes = bundled::themes();
        let theme = Resolved::new(&themes[1], None).unwrap();
        assert_eq!(
            render(&theme),
            include_str!("../tests/golden/ember.kitty.conf")
        );
    }

    /// A TOML basic string holding exactly `text`, every character escaped.
    fn toml_string(text: &str) -> String {
        let mut out = String::from("\"");
        for c in text.chars() {
            out.push_str(&format!("\\U{:08X}", c as u32));
        }
        out.push('"');
        out
    }

    /// Whatever a theme file puts in its text fields, the output is the two
    /// comment lines plus exactly one `key #rrggbb` line per key.
    #[test]
    fn hostile_text_never_reaches_the_output() {
        let hostile = [
            "x\ninclude /etc/passwd",
            "x\r\nbackground #000000",
            "\u{1b}]52;c;AAAA\u{7}",
            "\u{202e}evil",
            "# \\\n map ctrl+a launch sh",
            "\"\"\"",
            "*/ } </style> $(reboot) `id` {{x}}",
        ];
        let clean = render(&Resolved::new(&bundled::themes()[0], None).unwrap());
        for text in hostile {
            let quoted = toml_string(text);
            let src = bundled::SOURCES[0]
                .1
                .replacen("\"Aetherius\"", &quoted, 2)
                .replacen("\"Rafael Rueda\"", &quoted, 1)
                .replacen("\"MIT\"", &quoted, 1)
                .replacen("\"Starlit indigo with a periwinkle accent.\"", &quoted, 1);
            assert_eq!(src.matches(&quoted).count(), 5, "every text field replaced");
            let loaded = parse_theme(&src).unwrap();
            let out = render(&Resolved::new(&loaded.theme, None).unwrap());
            assert_eq!(out, clean, "text fields must not influence the output");
            let lines: Vec<&str> = out.lines().collect();
            assert_eq!(lines.len(), 2 + KEYS.len());
            for (line, key) in lines[2..].iter().zip(KEYS) {
                let (k, v) = line.split_once(' ').unwrap();
                assert_eq!(k, key);
                assert!(crate::Color::parse(v).is_ok(), "{line:?}");
            }
        }
    }
}
