//! Renderer for tmux: colours in, the text of `velatura.conf` out.

use std::fmt::Write;

use crate::Resolved;

/// Bumped whenever the set of options or their mapping changes.
pub const FORMAT: u32 = 1;

/// Every option this renderer sets, in output order. All of them exist
/// since tmux 2.9, so an older tmux does not stop at a line it does not
/// know. The connector uses the list to find lines in the user's file
/// that would override the theme.
pub const OPTIONS: [&str; 14] = [
    "status-style",
    "status-left-style",
    "status-right-style",
    "window-status-style",
    "window-status-current-style",
    "window-status-activity-style",
    "window-status-bell-style",
    "pane-border-style",
    "pane-active-border-style",
    "message-style",
    "message-command-style",
    "mode-style",
    "clock-mode-colour",
    "display-panes-active-colour",
];

pub fn render(theme: &Resolved<'_>) -> String {
    let ui = &theme.colors.ui;
    let on = |fg: crate::Color, bg: crate::Color| format!("fg={},bg={}", fg.hex(), bg.hex());
    let fg = |fg: crate::Color| format!("fg={}", fg.hex());
    let values = [
        on(ui.fg, ui.bg_dim),
        on(ui.fg_muted, ui.bg_dim),
        on(ui.fg_muted, ui.bg_dim),
        on(ui.fg_subtle, ui.bg_dim),
        format!("{},bold", on(ui.accent, ui.bg_dim)),
        on(ui.warning, ui.bg_dim),
        format!("{},bold", on(ui.error, ui.bg_dim)),
        fg(ui.border),
        fg(ui.accent),
        on(ui.fg, ui.surface),
        on(ui.fg, ui.surface),
        on(ui.selection_fg, ui.selection_bg),
        ui.accent.hex(),
        ui.accent.hex(),
    ];
    let mut out = String::new();
    out.push_str("# Generated by Velatura. Edits to this file are replaced on the next apply.\n");
    let _ = writeln!(
        out,
        "# theme {} fingerprint {} format {FORMAT}",
        theme.label(),
        theme.fingerprint()
    );
    for (option, value) in OPTIONS.iter().zip(values) {
        let _ = writeln!(out, "set -g {option} \"{value}\"");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bundled;

    #[test]
    fn golden() {
        let themes = bundled::themes();
        let golden = [
            include_str!("../tests/golden/aetherius.tmux.conf"),
            include_str!("../tests/golden/ember.tmux.conf"),
        ];
        for (theme, expected) in themes.iter().zip(golden) {
            assert_eq!(render(&Resolved::new(theme, None).unwrap()), expected);
        }
    }
}
