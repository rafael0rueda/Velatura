//! Renderer for GNOME Shell: colour overrides for a User Themes stylesheet.
//!
//! The Shell layers a user theme over its own stylesheet, so this is a short
//! list of colour declarations and nothing else. It never copies or imports
//! the stock stylesheet, which keeps the Shell's own layout, its light and
//! high-contrast variants, and whatever a future version adds.
//!
//! One syntax error makes the Shell reject the whole file, so the output is
//! built from fixed text and typed colours only, and a test checks its
//! structure. The accent is not overridden: the Shell uses the system accent
//! in some two hundred places, and restating them per version is out of
//! scope.

use std::fmt::Write;

use crate::{Color, Resolved};

/// Bumped whenever the rules change. Part of the theme folder's name, so a
/// new format makes the Shell load the new file.
pub const FORMAT: u32 = 1;

/// Every selector the overrides use. A test checks each one exists in the
/// stock stylesheet of every supported Shell version.
pub const SELECTORS: [&str; 17] = [
    "#panel",
    "#panel .panel-button",
    "#overviewGroup",
    ".popup-menu-content",
    ".candidate-popup-content",
    ".modal-dialog",
    ".run-dialog",
    ".app-folder-dialog",
    ".notification-banner",
    ".message",
    ".calendar",
    ".osd-window",
    ".switcher-list",
    ".resize-popup",
    ".search-entry",
    "#dash .dash-background",
    ".dash-label",
];

/// The folder name of the generated theme. It changes whenever the colours
/// or the rules do, because the Shell reloads only on a new name.
pub fn folder(theme: &Resolved<'_>) -> String {
    format!("Velatura-{}-{FORMAT}", &theme.fingerprint()[..10])
}

pub fn render(theme: &Resolved<'_>) -> String {
    render_with(theme, false)
}

/// The same rules for Velatura's own extension, whose stylesheet sits
/// beside those of other extensions instead of under them. Between two
/// rules of the same weight the Shell does not go by which came last, so
/// each selector's first part is written twice: one step heavier than the
/// plain `#panel` an extension typically uses, and still lighter than a
/// rule someone wrote on purpose for a narrower case.
pub fn render_for_extension(theme: &Resolved<'_>) -> String {
    render_with(theme, true)
}

/// `#panel .panel-button` as `#panel#panel .panel-button`.
fn heavier(selector: &str) -> String {
    let (first, rest) = match selector.split_once(' ') {
        Some((first, rest)) => (first, format!(" {rest}")),
        None => (selector, String::new()),
    };
    format!("{first}{first}{rest}")
}

fn render_with(theme: &Resolved<'_>, heavy: bool) -> String {
    let weigh = |selector: &str| {
        if heavy {
            heavier(selector)
        } else {
            selector.to_owned()
        }
    };
    let ui = &theme.colors.ui;
    let raised = ui.surface.mix(ui.fg, 0.06);
    // (selectors, background, text)
    let rules: [(&[&str], Color, Color); 6] = [
        (&["#panel"], ui.bg_dim, ui.fg),
        (&["#overviewGroup"], ui.bg, ui.fg),
        (
            &[
                ".popup-menu-content",
                ".candidate-popup-content",
                ".modal-dialog",
                ".run-dialog",
                ".app-folder-dialog",
                ".notification-banner",
                ".osd-window",
                ".switcher-list",
                ".resize-popup",
                ".dash-label",
            ],
            ui.surface,
            ui.fg,
        ),
        (&[".message", ".calendar"], raised, ui.fg),
        (&[".search-entry"], raised, ui.fg),
        (&["#dash .dash-background"], ui.surface, ui.fg),
    ];
    let mut out = String::new();
    out.push_str(
        "/* Generated by Velatura. Edits to this file are replaced on the next apply. */\n",
    );
    let _ = writeln!(
        out,
        "/* theme {} fingerprint {} format {FORMAT} */",
        theme.label(),
        theme.fingerprint()
    );
    for (selectors, background, text) in rules {
        let _ = writeln!(
            out,
            "{} {{ background-color: {}; color: {}; }}",
            selectors
                .iter()
                .map(|s| weigh(s))
                .collect::<Vec<_>>()
                .join(", "),
            background.hex(),
            text.hex()
        );
    }
    let _ = writeln!(
        out,
        "{} {{ color: {}; }}",
        weigh("#panel .panel-button"),
        ui.fg.hex()
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bundled;

    #[test]
    fn golden() {
        let themes = bundled::themes();
        let golden = [
            include_str!("../tests/golden/aetherius.shell.css"),
            include_str!("../tests/golden/ember.shell.css"),
        ];
        for (theme, expected) in themes.iter().zip(golden) {
            assert_eq!(render(&Resolved::new(theme, None).unwrap()), expected);
        }
    }

    /// The Shell drops the whole stylesheet on one syntax error, so the
    /// shape of every line is checked: selectors from the list, then only
    /// `property: #rrggbb;` declarations between one pair of braces.
    #[test]
    fn every_rule_is_well_formed_and_uses_known_selectors() {
        for theme in bundled::themes() {
            let out = render(&Resolved::new(&theme, None).unwrap());
            let mut used = Vec::new();
            for line in out.lines().skip(2) {
                let (selectors, rest) = line.split_once(" { ").expect(line);
                let body = rest.strip_suffix(" }").expect(line);
                assert!(!body.contains(['{', '}']), "{line}");
                for selector in selectors.split(", ") {
                    assert!(SELECTORS.contains(&selector), "{selector}");
                    used.push(selector);
                }
                for declaration in body.split_terminator(';') {
                    let (property, value) = declaration.trim().split_once(": ").expect(line);
                    assert!(matches!(property, "background-color" | "color"), "{line}");
                    assert!(Color::parse(value).is_ok(), "{line}");
                }
            }
            used.sort_unstable();
            let mut all = SELECTORS.to_vec();
            all.sort_unstable();
            assert_eq!(used, all, "every listed selector is used exactly once");
        }
    }

    /// For the extension the same rules, each selector one step heavier.
    #[test]
    fn the_extensions_rules_are_the_same_rules_made_heavier() {
        for theme in bundled::themes() {
            let resolved = Resolved::new(&theme, None).unwrap();
            let (plain, heavy) = (render(&resolved), render_for_extension(&resolved));
            assert_eq!(plain.lines().count(), heavy.lines().count());
            for (a, b) in plain.lines().zip(heavy.lines()).skip(2) {
                let (selectors, body) = a.split_once(" { ").unwrap();
                let (heavier_selectors, same_body) = b.split_once(" { ").unwrap();
                assert_eq!(body, same_body);
                let want: Vec<String> = selectors.split(", ").map(heavier).collect();
                assert_eq!(heavier_selectors, want.join(", "));
            }
            assert!(heavy.contains("#panel#panel { "));
            assert!(heavy.contains("#panel#panel .panel-button { "));
            assert!(heavy.contains(".dash-label.dash-label { "));
            assert!(heavy.contains("#dash#dash .dash-background { "));
        }
    }

    #[test]
    fn selectors_exist_in_the_stock_stylesheet() {
        // One fixture per supported Shell version, taken from its own theme.
        let versions = [
            (
                "47",
                include_str!("../tests/fixtures/shell-selectors-47.txt"),
            ),
            (
                "48",
                include_str!("../tests/fixtures/shell-selectors-48.txt"),
            ),
            (
                "49",
                include_str!("../tests/fixtures/shell-selectors-49.txt"),
            ),
            (
                "50",
                include_str!("../tests/fixtures/shell-selectors-50.txt"),
            ),
            (
                "51",
                include_str!("../tests/fixtures/shell-selectors-51.txt"),
            ),
        ];
        for (version, fixture) in versions {
            let stock: Vec<&str> = fixture.lines().collect();
            for selector in SELECTORS {
                assert!(
                    stock.contains(&selector),
                    "GNOME Shell {version} has no {selector}"
                );
            }
        }
    }

    /// Ubuntu's own session uses its own Shell stylesheet (Yaru), in a
    /// light and a dark form. The lists hold what both have.
    #[test]
    fn selectors_exist_in_ubuntus_stylesheet() {
        let versions = [
            (
                "47",
                include_str!("../tests/fixtures/shell-selectors-ubuntu-47.txt"),
            ),
            (
                "48",
                include_str!("../tests/fixtures/shell-selectors-ubuntu-48.txt"),
            ),
            (
                "49",
                include_str!("../tests/fixtures/shell-selectors-ubuntu-49.txt"),
            ),
            (
                "50",
                include_str!("../tests/fixtures/shell-selectors-ubuntu-50.txt"),
            ),
        ];
        for (version, fixture) in versions {
            let yaru: Vec<&str> = fixture.lines().collect();
            assert!(
                yaru.len() > 1000,
                "Ubuntu {version}: the list looks cut short"
            );
            for selector in SELECTORS {
                // A rule of its own, or named as the place other rules
                // apply in: either way the Shell still has the element.
                // (Ubuntu's 47 styles the Run dialog only through what is
                // inside it.)
                let inside = format!("{selector} ");
                assert!(
                    yaru.iter()
                        .any(|s| *s == selector || s.starts_with(&inside)),
                    "Ubuntu's GNOME Shell {version} has no {selector}"
                );
            }
        }
    }

    #[test]
    fn the_folder_name_follows_the_colours() {
        let themes = bundled::themes();
        let a = folder(&Resolved::new(&themes[0], None).unwrap());
        let b = folder(&Resolved::new(&themes[1], None).unwrap());
        assert_ne!(a, b);
        assert!(a.starts_with("Velatura-") && a.ends_with("-1"));
        assert!(a.bytes().all(|c| c.is_ascii_alphanumeric() || c == b'-'));
    }
}
