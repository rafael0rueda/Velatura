//! Renderer for Firefox: the colour variables of its own window, for the
//! stylesheet `userChrome.css` loads.
//!
//! Firefox colours its window from a set of design variables declared on
//! the document's root: the tab strip, the toolbar, the address field,
//! menus and the sidebar. The output sets those, and the colour scheme,
//! on `:root` and nothing else: no selectors, so it cannot change shapes,
//! and a variable a newer Firefox no longer reads does nothing at all.
//!
//! The file is loaded as a user stylesheet. In the cascade a user's
//! ordinary declarations lose to Firefox's own, and their `!important`
//! ones win, so every declaration carries it.

use std::fmt::Write;

use crate::{Appearance, Color, Resolved};

/// Bumped whenever the set of variables or their mapping changes.
pub const FORMAT: u32 = 1;

/// Every variable this renderer sets, with its value, in output order. A
/// test checks each one is read by Firefox's own stylesheets.
pub fn colors(theme: &Resolved<'_>) -> Vec<(&'static str, Color)> {
    let ui = &theme.colors.ui;
    let hover = ui.bg.mix(ui.fg, 0.12);
    let active = ui.bg.mix(ui.fg, 0.22);
    vec![
        // The tab strip and the window around everything.
        ("--toolbox-background-color", ui.bg_dim),
        ("--toolbox-background-color-inactive", ui.bg_dim),
        ("--toolbox-text-color", ui.fg),
        ("--toolbox-text-color-inactive", ui.fg_muted),
        ("--tab-background-color-selected", ui.bg),
        ("--tab-text-color-selected", ui.fg),
        ("--tab-loading-fill", ui.accent),
        // The toolbar and its buttons.
        ("--toolbar-background-color", ui.bg),
        ("--toolbar-text-color", ui.fg),
        ("--toolbarbutton-icon-fill", ui.fg),
        ("--toolbarbutton-background-color-hover", hover),
        ("--toolbarbutton-background-color-active", active),
        ("--toolbarbutton-icon-fill-attention", ui.accent),
        ("--toolbarbutton-icon-fill-attention-text", ui.accent_fg),
        ("--toolbarseparator-color", ui.border),
        ("--chrome-content-separator-color", ui.border),
        // The address and search fields, and the results under them.
        ("--toolbar-field-background-color", ui.surface),
        ("--toolbar-field-text-color", ui.fg),
        ("--toolbar-field-border-color", ui.border),
        ("--toolbar-field-background-color-focus", ui.surface),
        ("--toolbar-field-text-color-focus", ui.fg),
        ("--toolbar-field-border-color-focus", ui.accent),
        ("--urlbarview-background-color-selected", ui.selection_bg),
        ("--urlbarview-text-color-selected", ui.selection_fg),
        // Menus and panels.
        ("--panel-background-color", ui.surface),
        ("--panel-text-color", ui.fg),
        ("--panel-border-color", ui.border),
        ("--input-text-background-color", ui.bg_dim),
        ("--input-text-color", ui.fg),
        // The sidebar, and the page area before a page has drawn.
        ("--sidebar-background-color", ui.bg),
        ("--sidebar-text-color", ui.fg),
        ("--sidebar-border-color", ui.border),
        ("--tabpanel-background-color", ui.bg),
        // The accent: primary buttons, focus rings, selected items, links.
        ("--color-accent-primary", ui.accent),
        ("--button-text-color-primary", ui.accent_fg),
        ("--focus-outline-color", ui.accent),
        ("--color-accent-primary-selected", ui.selection_bg),
        ("--text-color-accent-primary-selected", ui.selection_fg),
        ("--link-color", ui.link),
    ]
}

/// The variables [`colors`] sets. The connector uses them to find rules in
/// the user's `userChrome.css` that would override the theme.
pub fn names(theme: &Resolved<'_>) -> Vec<&'static str> {
    colors(theme).into_iter().map(|(name, _)| name).collect()
}

pub fn render(theme: &Resolved<'_>) -> String {
    let scheme = match theme.colors.appearance {
        Appearance::Dark => "dark",
        Appearance::Light => "light",
    };
    let mut out = String::new();
    out.push_str(
        "/* Generated by Velatura. Edits to this file are replaced on the next apply. */\n",
    );
    let _ = writeln!(
        out,
        "/* theme {} fingerprint {} format {FORMAT} */",
        theme.label(),
        theme.fingerprint()
    );
    out.push_str(":root {\n");
    let _ = writeln!(out, "  color-scheme: {scheme} !important;");
    for (name, color) in colors(theme) {
        let _ = writeln!(out, "  {name}: {} !important;", color.hex());
    }
    out.push_str("}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bundled;

    #[test]
    fn golden() {
        let themes = bundled::themes();
        let golden = [
            include_str!("../tests/golden/aetherius.firefox.css"),
            include_str!("../tests/golden/ember.firefox.css"),
        ];
        for (theme, expected) in themes.iter().zip(golden) {
            assert_eq!(render(&Resolved::new(theme, None).unwrap()), expected);
        }
    }

    /// Only declarations on the root, each one important, each a fixed
    /// name and a colour. No name is set twice.
    #[test]
    fn output_is_only_root_declarations() {
        for theme in bundled::themes() {
            let r = Resolved::new(&theme, None).unwrap();
            let out = render(&r);
            let lines: Vec<&str> = out.lines().skip(2).collect();
            assert_eq!(lines.first(), Some(&":root {"));
            assert_eq!(lines.last(), Some(&"}"));
            for line in &lines[2..lines.len() - 1] {
                let (name, value) = line
                    .trim_start()
                    .strip_suffix(" !important;")
                    .and_then(|l| l.split_once(": "))
                    .expect(line);
                assert!(name.starts_with("--"), "{line}");
                assert!(Color::parse(value).is_ok(), "{line}");
            }
            let mut seen = names(&r);
            let all = seen.len();
            seen.sort_unstable();
            seen.dedup();
            assert_eq!(seen.len(), all);
        }
    }

    /// Every variable set is one Firefox's own stylesheets read, in each
    /// version a list was taken from. A renamed variable would do nothing
    /// and say nothing, so this is where it shows.
    #[test]
    fn every_variable_is_read_by_firefox() {
        let lists = [(
            "157",
            include_str!("../tests/fixtures/firefox-variables-157.txt"),
        )];
        let theme = &bundled::themes()[0];
        let r = Resolved::new(theme, None).unwrap();
        for (version, list) in lists {
            let read: Vec<&str> = list.lines().collect();
            for name in names(&r) {
                assert!(
                    read.contains(&name),
                    "Firefox {version} does not read {name}"
                );
            }
        }
    }
}
