//! Renderer for Ptyxis: colours in, the text of `velatura.palette` out.
//!
//! The keys are the ones every palette that comes with Ptyxis has. A
//! palette holds a light and a dark set, and Ptyxis takes the one that
//! matches the style in use; a theme is one or the other, so both sets
//! are the theme's, and the terminal shows it under either style.

use std::fmt::Write;

use crate::Resolved;

/// Bumped whenever the set of keys or their mapping changes.
pub const FORMAT: u32 = 1;

/// The palette's id: the file's name without `.palette`, and the value of
/// a profile's `palette` setting.
pub const ID: &str = "velatura";

/// The keys of each set besides `Color0` to `Color15`, in output order.
pub const KEYS: [&str; 3] = ["Foreground", "Background", "Cursor"];

pub fn render(theme: &Resolved<'_>) -> String {
    let ui = &theme.colors.ui;
    let mut out = String::new();
    out.push_str("# Generated by Velatura. Edits to this file are replaced on the next apply.\n");
    let _ = writeln!(
        out,
        "# theme {} fingerprint {} format {FORMAT}",
        theme.label(),
        theme.fingerprint()
    );
    out.push_str("[Palette]\nName=Velatura\n");
    for set in ["Light", "Dark"] {
        let _ = writeln!(out, "\n[{set}]");
        for (key, color) in KEYS.iter().zip([ui.fg, ui.bg, ui.cursor]) {
            let _ = writeln!(out, "{key}={}", color.hex());
        }
        for (i, color) in theme.colors.ansi.iter().enumerate() {
            let _ = writeln!(out, "Color{i}={}", color.hex());
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bundled;

    #[test]
    fn golden() {
        let themes = bundled::themes();
        let golden = [
            include_str!("../tests/golden/aetherius.ptyxis.palette"),
            include_str!("../tests/golden/ember.ptyxis.palette"),
        ];
        for (theme, expected) in themes.iter().zip(golden) {
            assert_eq!(render(&Resolved::new(theme, None).unwrap()), expected);
        }
    }
}
